interface GenArgs {
  prompt: string;
  aspectRatio: string;
  quality: "standard" | "max";
  sources: ImagePart[];
  operation: "generate" | "edit" | "blend";
}

async function runImageModel(ctx: ToolCtx, args: GenArgs): Promise<string | ToolOutput> {
  const cfg = await getImageConfig();
  const cred = await getGoogleCredential(cfg.credentialId);
  if (!cred) {
    return "Error: image generation isn't configured (no Google credential on this server — an admin can add one).";
  }

  const model = args.quality === "max" ? PRO_MODEL : FLASH_MODEL;
  const limit = args.quality === "max" ? cfg.proWeeklyLimit : cfg.flashWeeklyLimit;
  const used = await usedThisWeek(ctx.userId, model);
  if (used >= limit) {
    // Each tier has its own counter, so a helpful model could silently hop
    // tiers and the user would never learn a quota exists (found in owner
    // testing) — the refusal must demand transparency, not suggest a bypass.
    // Guidance sits behind the marker: the image placeholder shows only the
    // user-facing sentence.
    const other = args.quality === "max" ? "standard" : "max";
    return (
      `Error: weekly image quota reached — ${used}/${limit} "${args.quality}"-quality images ` +
      `in the last 7 days (the rolling window frees up as older generations age out). ` +
      `[To the assistant: tell the user plainly that their weekly ${args.quality}-quality image ` +
      `allowance is used up. Do NOT silently retry at "${other}" quality — it has its own separate ` +
      `quota${args.quality === "standard" ? " and costs more" : ""}; you may OFFER it as an explicit choice.]`
    );
  }

  const ai = new GoogleGenAI({ apiKey: cred.secret });
  const parts: Record<string, unknown>[] = [
    ...args.sources.map((s) => ({
      inlineData: { mimeType: s.mimeType, data: s.dataBase64 },
    })),
    { text: args.prompt },
  ];

  // Retry loop: retry on transient THROWS (5xx/overload/rate-limit) AND on an
  // EMPTY response (the API returns no image part but no error — also usually
  // transient/rate-limit). A response with explanatory TEXT (a refusal) is a
  // content decision, not transient → surface it, don't retry. Only break with
  // a valid image in hand.
  let img: { inlineData: { mimeType?: string; data?: string } } | undefined;
  let usageMetadata: Awaited<ReturnType<typeof ai.models.generateContent>>["usageMetadata"];
  let lastErr: unknown;
  const genT0 = Date.now(); // time the actual generation, for the ETA estimate
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      const res = await ai.models.generateContent({
        model,
        contents: [{ role: "user", parts }],
        config: {
          responseModalities: ["IMAGE"],
          imageConfig: {
            aspectRatio: args.aspectRatio,
            imageSize: args.quality === "max" ? "2K" : "1K",
          },
          // Fresh timeout per attempt (a used signal would abort instantly).
          abortSignal: AbortSignal.timeout(TIMEOUT_MS),
        },
      });
      const outParts = res.candidates?.[0]?.content?.parts ?? [];
      const found = outParts.find(
        (p): p is { inlineData: { mimeType?: string; data?: string } } =>
          !!(p as { inlineData?: unknown }).inlineData,
      );
      if (found?.inlineData?.data) {
        img = found;
        usageMetadata = res.usageMetadata; // captured for billing after the loop
        break;
      }
      // No image. If the model explained itself, it's a refusal — don't retry.
      const text = outParts.map((p) => (p as { text?: string }).text ?? "").join(" ").trim();
      if (text) {
        await appLog("warn", "image", `Image ${args.operation}: model returned text, no image`, {
          userId: ctx.userId, details: { model, text: text.slice(0, 300) },
        });
        return `Error: the model returned no image (it said: ${text.slice(0, 200)}).`;
      }
      // Empty response → transient; retry.
      lastErr = new Error("empty response (no image part)");
      await appLog(attempt < MAX_ATTEMPTS ? "warn" : "error", "image", `Image ${args.operation}: empty response (attempt ${attempt}/${MAX_ATTEMPTS})`, {
        userId: ctx.userId, details: { model, attempt },
      });
      if (attempt < MAX_ATTEMPTS) await new Promise((r) => setTimeout(r, 800 * attempt));
    } catch (e) {
      lastErr = e;
      const retryable = isTransientImageError(e) && attempt < MAX_ATTEMPTS;
      await appLog(retryable ? "warn" : "error", "image", `Image ${args.operation} failed (attempt ${attempt}/${MAX_ATTEMPTS})`, {
        userId: ctx.userId,
        details: { model, attempt, retryable, error: (e instanceof Error ? e.message : String(e)).slice(0, 400) },
      });
      if (!retryable) break;
      await new Promise((r) => setTimeout(r, 800 * attempt)); // 0.8s, 1.6s backoff
    }
  }
  if (!img?.inlineData?.data) {
    const m = lastErr instanceof Error ? lastErr.message.slice(0, 300) : String(lastErr);
    // Gemini's image models sometimes 500 INTERNAL on a specific prompt+image
    // combination rather than failing cleanly (seen live: two elaborate blend
    // prompts 500'd 3/3 while a plain one with the SAME sources succeeded
    // seconds later) — so steer the retry toward a simpler prompt, not a
    // verbatim re-run. Guidance behind the marker: users see only the first
    // sentence in the image placeholder.
    return `Error: image ${args.operation} failed after ${MAX_ATTEMPTS} attempt(s): ${m}. This is often a temporary Google-side issue. [To the assistant: elaborate prompts can trigger this repeatedly — retry once with a NOTICEABLY shorter, simpler prompt (same source images are fine).]`;
  }

  const mime = img.inlineData.mimeType ?? "image/png";
  const ext = mime.includes("jpeg") ? "jpg" : mime.includes("webp") ? "webp" : "png";
  const buffer = Buffer.from(img.inlineData.data, "base64");
  const stored = await saveBufferToPool(
    ctx.conversationId,
    `${args.operation}-${new Date().toISOString().slice(0, 19).replace(/[-:T]/g, "")}.${ext}`,
    buffer,
    await getMaxUploadBytes(),
  );
  const row = await db.file.create({
    data: {
      userId: ctx.userId,
      conversationId: ctx.conversationId,
      filename: stored.storedName,
      mimeType: mime,
      detectedMime: mime,
      sizeBytes: BigInt(stored.sizeBytes),
      storagePath: stored.storagePath,
      kind: "generated",
      meta: {
        operation: args.operation,
        model,
        prompt: args.prompt.slice(0, 500),
        aspectRatio: args.aspectRatio,
        genMs: Date.now() - genT0,
      },
    },
  });

  // Bill the image: flat per-image cost + whatever tokens the call reported.
  const um = usageMetadata;
  await db.usageRecord.create({
    data: {
      userId: ctx.userId,
      role: "image",
      provider: "google",
      model,
      inputTokens: um?.promptTokenCount ?? 0,
      outputTokens: um?.candidatesTokenCount ?? 0,
      cacheReadTokens: 0,
      cacheWriteTokens: 0,
      costEstimate: IMAGE_COST[model] ?? 0.067,
    },
  });

  return {
    text:
      `Created "${stored.storedName}" (${mime}, ${args.aspectRatio}, ${args.quality}) — saved to this ` +
      `conversation's files and attached for your review. Weekly quota: ${used + 1}/${limit}.`,
    images: [{ mimeType: mime, dataBase64: img.inlineData.data }],
    artifact: {
      fileId: row.id,
      mimeType: mime,
      aspectRatio: args.aspectRatio,
      prompt: args.prompt,
      operation: args.operation,
      genMs: Date.now() - genT0,
    },
  };
}

