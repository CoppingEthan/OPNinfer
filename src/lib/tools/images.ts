function commonArgs(args: Record<string, unknown>) {
  const aspect = String(args.aspect_ratio ?? "1:1");
  return {
    prompt: String(args.prompt ?? "").trim(),
    aspectRatio: ASPECT_RATIOS.has(aspect) ? aspect : "1:1",
    quality: (args.quality === "max" ? "max" : "standard") as "standard" | "max",
  };
}

export async function executeImageGeneration(
  args: Record<string, unknown>,
  ctx: ToolCtx,
): Promise<string | ToolOutput> {
  const base = commonArgs(args);
  if (!base.prompt) return "Error: prompt is required.";
  return runImageModel(ctx, { ...base, sources: [], operation: "generate" });
}

export async function executeImageEdit(
  args: Record<string, unknown>,
  ctx: ToolCtx,
): Promise<string | ToolOutput> {
  const base = commonArgs(args);
  if (!base.prompt) return "Error: prompt is required.";
  const name = String(args.image ?? "").trim();
  if (!name) return "Error: image (source filename) is required.";
  const src = await loadImageByName(ctx.conversationId, name, base.quality);
  if (typeof src === "string") return src;
  return runImageModel(ctx, { ...base, sources: [src], operation: "edit" });
}

export async function executeImageBlend(
  args: Record<string, unknown>,
  ctx: ToolCtx,
): Promise<string | ToolOutput> {
  const base = commonArgs(args);
  if (!base.prompt) return "Error: prompt is required.";
  const names = Array.isArray(args.images) ? args.images.map(String) : [];
  if (names.length < 2 || names.length > 4) {
    return "Error: provide 2-4 source image filenames.";
  }
  const sources: ImagePart[] = [];
  for (const n of names) {
    const src = await loadImageByName(ctx.conversationId, n.trim(), base.quality);
    if (typeof src === "string") return src;
    sources.push(src);
  }
  return runImageModel(ctx, { ...base, sources, operation: "blend" });
}
