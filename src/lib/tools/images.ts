/**
 * Image generation / edit / blend — Gemini ONLY (the owner's call: no
 * fallback backend, no cascade; failures are honest tool errors). Outputs
 * land in the conversation pool as kind=generated files (worker ingests →
 * manifest/chips), and ride back to the model as a vision part so it can
 * check its own work. Per-user rolling 7-day quotas per tier — counted
 * straight off usage_records (no extra table).
 */

const FLASH_MODEL = process.env.GEMINI_IMAGE_FLASH_MODEL ?? "gemini-3.1-flash-image";
const PRO_MODEL = process.env.GEMINI_IMAGE_PRO_MODEL ?? "gemini-3-pro-image";
const TIMEOUT_MS = 180_000;
/** Retry transient Google failures (5xx / overloaded / rate-limit / network),
 *  which are common on the preview image models — a single blip shouldn't fail
 *  the whole request (this was the symptom behind "temporary issue"). */
const MAX_ATTEMPTS = 3;

/** Transient = worth retrying: numeric-5xx/429 (isRetryableError) OR a message
 *  the SDK surfaces without a numeric status (UNAVAILABLE / overloaded / …). */
function isTransientImageError(e: unknown): boolean {
  if (isRetryableError(e)) return true;
  const msg = (e instanceof Error ? e.message : String(e)).toLowerCase();
  return /(overload|unavailable|deadline|timeout|try again|rate.?limit|resource.?exhausted|internal error|temporarily|\b50[0-9]\b|\b429\b)/.test(msg);
}

/** Flat USD cost per image (1K/2K bill the same tier on Gemini). */
const IMAGE_COST: Record<string, number> = {
  [FLASH_MODEL]: Number(process.env.GEMINI_FLASH_IMAGE_COST ?? 0.067),
  [PRO_MODEL]: Number(process.env.GEMINI_PRO_IMAGE_COST ?? 0.134),
};

const ASPECT_RATIOS = new Set([
  "1:1", "16:9", "9:16", "4:3", "3:4", "3:2", "2:3", "4:5", "5:4", "21:9",
]);

export interface ImageToolsConfig {
  /** Pin a specific google credential; default = first google org key. */
  credentialId?: string;
  flashWeeklyLimit?: number;
  proWeeklyLimit?: number;
}

async function getImageConfig(): Promise<Required<Omit<ImageToolsConfig, "credentialId">> & ImageToolsConfig> {
  const cfg = (await getSetting<ImageToolsConfig>("image_tools_config")) ?? {};
  return {
    ...cfg,
    flashWeeklyLimit: cfg.flashWeeklyLimit ?? Number(process.env.GEMINI_FLASH_WEEKLY_LIMIT ?? 20),
    proWeeklyLimit: cfg.proWeeklyLimit ?? Number(process.env.GEMINI_PRO_WEEKLY_LIMIT ?? 5),
  };
}

async function getGoogleCredential(pinnedId?: string): Promise<Credential | null> {
  if (pinnedId) return loadCredential(pinnedId);
  const row = await db.providerCredential.findFirst({
    where: { provider: "google" },
    orderBy: { createdAt: "asc" },
  });
  return row ? loadCredential(row.id) : null;
}

/** Images generated by this user on this model in the rolling window. */
/** Estimated generation time (ms) from the last few real generations of this
 *  operation — powers the placeholder's live countdown. Reads genMs from
 *  recent replies' `meta.images` (app-owned; the ingestion worker rewrites the
 *  file meta, so that's not reliable). Falls back to a sane default before any
 *  history exists. */
const estimateCache = new Map<string, { at: number; ms: number }>();
const ESTIMATE_TTL_MS = 10 * 60_000;

export async function estimateImageMs(operation?: string): Promise<number> {
  const DEFAULT_MS = 14_000;
  // Cached: this runs INSIDE the turn, before the image placeholder is emitted,
  // and it only feeds a countdown. Ten minutes of staleness costs nothing and
  // keeps a database read off the hot path.
  const key = operation ?? "*";
  const hit = estimateCache.get(key);
  if (hit && Date.now() - hit.at < ESTIMATE_TTL_MS) return hit.ms;
  const rows = await db.message.findMany({
    where: { role: "assistant" },
    orderBy: { createdAt: "desc" },
    take: 40,
    select: { meta: true },
  });
  const times: number[] = [];
  for (const r of rows) {
    const imgs = (r.meta as { images?: { genMs?: number; operation?: string }[] } | null)?.images;
    if (!imgs) continue;
    for (const im of imgs) {
      if (typeof im.genMs === "number" && im.genMs > 0 && (!operation || im.operation === operation)) {
        times.push(im.genMs);
      }
    }
    if (times.length >= 8) break;
  }
  if (times.length === 0) {
    estimateCache.set(key, { at: Date.now(), ms: DEFAULT_MS });
    return DEFAULT_MS;
  }
  const recent = times.slice(0, 8);
  const ms = Math.round(recent.reduce((a, b) => a + b, 0) / recent.length);
  estimateCache.set(key, { at: Date.now(), ms });
  return ms;
}

async function usedThisWeek(userId: string, model: string): Promise<number> {
  const weekAgo = new Date(Date.now() - 7 * 864e5);
  return db.usageRecord.count({
    where: { userId, role: "image", model, createdAt: { gte: weekAgo } },
  });
}

